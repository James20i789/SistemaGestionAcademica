CREATE TABLE student (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document VARCHAR(40) NOT NULL UNIQUE,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    gender VARCHAR(30) NOT NULL,
    section VARCHAR(40) NOT NULL
);

CREATE TABLE teacher (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document VARCHAR(40) NOT NULL UNIQUE,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    specialty VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE
);

CREATE TABLE account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    name VARCHAR(160) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(12) NOT NULL CHECK (role IN ('ADMIN', 'TEACHER', 'STUDENT')),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    session_version BIGINT NOT NULL DEFAULT 1,
    teacher_id BIGINT UNIQUE REFERENCES teacher(id),
    student_id BIGINT UNIQUE REFERENCES student(id),
    CONSTRAINT valid_account_profile CHECK (
        (role = 'ADMIN' AND teacher_id IS NULL AND student_id IS NULL) OR
        (role = 'TEACHER' AND teacher_id IS NOT NULL AND student_id IS NULL) OR
        (role = 'STUDENT' AND student_id IS NOT NULL AND teacher_id IS NULL)
    )
);

CREATE TABLE course (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(160) NOT NULL,
    teacher_id BIGINT NOT NULL REFERENCES teacher(id),
    capacity INTEGER NOT NULL CHECK (capacity BETWEEN 1 AND 5000),
    section VARCHAR(40) NOT NULL
);

CREATE TABLE enrollment (
    course_id BIGINT REFERENCES course(id),
    student_id BIGINT REFERENCES student(id),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (course_id, student_id)
);

CREATE TABLE attendance (
    course_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    on_date DATE NOT NULL,
    status VARCHAR(16) CHECK (status IN ('PRESENTE','AUSENTE','TARDANZA','JUSTIFICACION')),
    PRIMARY KEY (course_id, on_date, student_id),
    FOREIGN KEY (course_id, student_id) REFERENCES enrollment(course_id, student_id)
);

CREATE TABLE schedule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES course(id),
    weekday INTEGER NOT NULL CHECK (weekday BETWEEN 1 AND 7),
    starts_at TIME NOT NULL,
    ends_at TIME NOT NULL,
    room VARCHAR(100) NOT NULL,
    CHECK (starts_at < ends_at)
);

CREATE TABLE assessment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES course(id),
    title VARCHAR(160) NOT NULL,
    on_date DATE NOT NULL,
    UNIQUE (id, course_id)
);

CREATE TABLE grade (
    assessment_id BIGINT NOT NULL,
    course_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    score DECIMAL(5,2) NOT NULL CHECK (score BETWEEN 0 AND 20),
    PRIMARY KEY (assessment_id, student_id),
    FOREIGN KEY (assessment_id, course_id) REFERENCES assessment(id, course_id) ON DELETE CASCADE,
    FOREIGN KEY (course_id, student_id) REFERENCES enrollment(course_id, student_id)
);

CREATE INDEX course_teacher ON course(teacher_id);
CREATE INDEX enrollment_student ON enrollment(student_id, course_id);
CREATE INDEX attendance_date ON attendance(on_date);
CREATE INDEX attendance_student ON attendance(student_id);
CREATE INDEX schedule_course ON schedule(course_id);
CREATE INDEX assessment_course ON assessment(course_id);

CREATE TABLE legacy_attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_name VARCHAR(201) NOT NULL,
    on_date DATE NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('PRESENTE','AUSENTE','TARDANZA','JUSTIFICACION')),
    UNIQUE(student_name, on_date, status)
);
